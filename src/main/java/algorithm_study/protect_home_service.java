package algorithm_study;

import java.util.*;
import java.io.*;

public class protect_home_service {
	static int N;
	static int credit;
	static int total_credit;
	static int max_K;
	static int max_home;
	static Deque<int[]> queue = new ArrayDeque<>(); // y, x, level
	static int[][] visited;
	static int[][] map;
	static Scanner sc = new Scanner(System.in);
	static int[] dx = {0, 1, 0, -1};
	static int[] dy = {-1, 0, 1, 0};
	
	public static void main(String[] args) {
		int TC = sc.nextInt();
		for (int t = 1; t <= TC; t ++) {
			
			N = sc.nextInt();
			credit = sc.nextInt();
			total_credit = credit * N * N;
			map = new int[N][N];			
			visited = new int[N][N];			
			
			// 최대 K 계산
			max_K = 1;
			while (true) {
				if ((max_K*max_K + (max_K-1)*(max_K-1)) > total_credit)
					break ;
				max_K ++;
			}
			
			// map 그리기
			for (int i = 0; i < N; i ++) {
				for (int j = 0; j < N; j ++) {
					map[i][j] = sc.nextInt();
				}
			}
			
			// 시뮬
			max_home = 0;
			for (int i = 0; i < N; i ++) {
				for (int j = 0; j < N; j ++) {
					cal_homeN(i, j);
				}
			}
			
			System.out.println("#"+t+" "+max_home);
		}
	}
	
	// 
	static void cal_homeN(int y, int x) {
		// map, queue 초기화
		queue.clear();
		for (int i = 0; i < N; i ++) {
			for (int j = 0; j < N; j ++) {
				visited[i][j] = 0;
			}
		}
		
		// 큐 시작
		queue.add(new int[] {y, x, 1});
		int[] homeN = new int[max_K + 1]; // 각 K당 집 수
		visited[y][x] = 1;
		
		// 하나의 블럭에서 K당 몇 개의 집이 추가되는지 구함
		while (!queue.isEmpty()) {
			int size = queue.size(); 
			
			int[] temp = queue.peek();
			if (temp[2] > max_K) { // 현재 K가 max_K보다 커지면 종료
				break;
			}
			
			homeN[temp[2]] = homeN[temp[2] - 1]; // 집 갯수 누적합
			
			for (int i = 0; i < size; i ++) {
				int[] cur = queue.poll();
				
				if (map[cur[0]][cur[1]] == 1) { // 해당 좌표가 집이라면 현재 K level의 집 갯수 증가
						homeN[cur[2]]++;
				}
				
				for (int dir = 0; dir < 4; dir++) {
					int nextY = cur[0] + dy[dir];
					int nextX = cur[1] + dx[dir];
					
					if (nextY < 0 || nextY >= N || nextX < 0 || nextX >= N) {
						continue;
					}
					
					if (visited[nextY][nextX] == 0) {
						queue.add(new int[] {nextY, nextX, cur[2] + 1});
						visited[nextY][nextX] = 1;
					}
				}
			}
		}
		
		// 해당 블럭에 방범대를 설치했을 때 최대로 수용 가능한 집 수
		for (int i = max_K; i > 0; i --) {
			if ((i * i + (i - 1) * (i - 1)) <= homeN[i] * credit) {
				max_home = Math.max(homeN[i], max_home);
				break ;
			}
		}
	}
}

