// swea 보급로 문제임 / clim_mountain_dijkstra, jungol fix_load 다시 풀어보기
public class supply_route_dijkstra {

	static PriorityQueue<int[]> pq = new PriorityQueue<>((a,b) -> Integer.compare(a[2], b[2]));
	static int[][] distance;
	static int[][] map;
	static Scanner sc = new Scanner(System.in);
	static int[] dx = {0, 1, 0, -1}; // 북, 동, 남, 서
	static int[] dy = {-1, 0, 1, 0};
	
	public static void main(String[] args) {
		int TC = sc.nextInt();
		
		for (int t = 1; t<=TC; t++) {
			int N = sc.nextInt();
			
			map = new int[N][N];
			distance = new int[N][N];
			String st;
			sc.nextLine();
			pq.clear();
			
			for (int i = 0;i<N;i++) {
				st = sc.nextLine();
				for(int j=0;j<N;j++) {
					map[i][j] = st.charAt(j) - '0';
					distance[i][j] = Integer.MAX_VALUE;
				}
			}
			
			distance[0][0] = 0;
			pq.offer(new int[] {0, 0, 0});
			
			// 다잌 시뮬
			while (!pq.isEmpty()) {
				int[] cur = pq.poll();
				
				// 처음 poll된 좌표는 무조건 해당 경로 최소값임
				if (cur[0] == N-1 && cur[1] == N-1) {
					System.out.println("#"+t+" "+cur[2]);
					break ;
				}
				
				// pq에서 꺼낸 경로 가중치가 최적이 아닌 경우 건너띄우기
				if (distance[cur[0]][cur[1]] < cur[2])
					continue ;
				
				for (int i = 0; i < 4; i ++) {
					
					int nextX = cur[1] + dx[i]; 
					int nextY = cur[0] + dy[i];
					
					if (nextX < 0 || nextX >= N || nextY < 0 || nextY >= N)
						continue;
					
					int nextW = distance[cur[0]][cur[1]] + map[nextY][nextX];
					
					// 생성한 다음 경로 가중치가 이미 구한 가중치보다 큰 경우 필터링 (>가 아니라 >=여야 함)
					if (nextW >= distance[nextY][nextX])
						continue;
					
					pq.offer(new int[] {nextY, nextX, nextW});
					distance[nextY][nextX] = nextW;
				}
			}
		}
	}
}
