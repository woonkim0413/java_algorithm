package algorithm_study;

import java.util.*;
import java.io.*;

public class stack___cutting_Iron_lods_5432 {
	
	static int initialRods = 0;
	static int createIron = 0;
	static int curHier = 0;
	static BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
	
	public static void main(String[] args) throws IOException {
		int CN = Integer.parseInt(br.readLine());
		
		for (int N = 1; N <= CN; N++) {
			String str = br.readLine();
			
			initialRods = 0;
			createIron = 0;
			curHier = 0;
			
			calIron(str);
			
			System.out.println("#"+N+" "+(initialRods+createIron));
		}
	}
	
	static private void calIron(String str) {
		for (int i = 0; i < str.length(); i++) {
			char curPart = str.charAt(i);
			
			switch(curPart) {
			
			case '(':
				// 일단 쇠막대가 하나 시작했다고 가정
				curHier++;
				break;
				
			case ')':
				// 레이저인 경우나 실제 쇠막대가 끝나는 지점이니 Hierachy 감소
				curHier--;
				
				if (str.charAt(i - 1) == '(') {			
					// 현재 존재하는 쇠막대들을 레이저가 자름
					createIron += curHier;
				}
				// 쇠 막대가 끝남
				else {
					initialRods++;
				}
				break;
			}
		}
	}
}

